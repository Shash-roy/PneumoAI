            "# 1. Get predictions on Validation Set\n",
            "_, _, _, y_val_true, y_val_prob = run_epoch(model, val_loader, finetune_criterion)\n",
            "\n",
            "# 2. Find optimal threshold targeting ~95% Recall\n",
            "thresholds = np.linspace(0.01, 0.99, 500)\n",
            "optimal_threshold = 0.5\n",
            "candidates = []\n",
            "for t in thresholds:\n",
            "    y_pred = (y_val_prob >= t).astype(int)\n",
            "    rec = recall_score(y_val_true, y_pred, zero_division=0)\n",
            "    prec = precision_score(y_val_true, y_pred, zero_division=0)\n",
