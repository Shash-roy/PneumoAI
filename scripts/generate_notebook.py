            "# Load ImageNet Pretrained ResNet-18\n",
            "model = models.resnet18(weights=models.ResNet18_Weights.DEFAULT)\n",
            "\n",
            "# Freeze all backbone feature extraction layers\n",
            "for param in model.parameters():\n",
