            "import cv2\n",
            "\n",
            "class GradCAMNotebook:\n",
            "    def __init__(self, model, target_layer):\n",
            "        self.model = model\n",
            "        self.target_layer = target_layer\n",
            "        self.gradients = None\n",
            "        self.activations = None\n",
            "        target_layer.register_forward_hook(self.forward_hook)\n",
            "        target_layer.register_full_backward_hook(self.backward_hook)\n",
            "        \n",
            "    def forward_hook(self, m, i, o):\n",
            "        self.activations = o.detach()\n",
            "        \n",
            "    def backward_hook(self, m, gi, go):\n",
            "        self.gradients = go[0].detach()\n",
            "        \n",
            "    def __call__(self, tensor, target_cls):\n",
            "        self.model.zero_grad()\n",
            "        out = self.model(tensor)\n",
            "        score = out[0, target_cls]\n",
            "        score.backward(retain_graph=True)\n",
            "        \n",
            "        weights = torch.mean(self.gradients, dim=(2, 3))[0]\n",
            "        cam = torch.zeros(self.activations.shape[2:], device=tensor.device)\n",
            "        for i, w in enumerate(weights):\n",
            "            cam += w * self.activations[0, i, :, :]\n",
            "            \n",
            "        cam = torch.relu(cam).cpu().numpy()\n",
            "        cam = (cam - cam.min()) / (cam.max() - cam.min() + 1e-8)\n",
            "        return cam\n",
